/**
 * 꿈 소재별 **민간 해석** 짧은 풀이.
 *
 * ── 왜 프론트 상수인가 ────────────────────────────────────────────────
 * 백엔드 계약(`/api/dream/keywords`)은 표제어와 슬러그만 준다. 풀이 본문을 받으려면
 * 계약과 스키마를 늘려야 하는데, **검색에 내보내는 소재는 아래 30개뿐이다**
 * (→ lib/site.ts `DREAM_INDEXED_KEYWORDS`). 서른 덩이의 고정 텍스트를 위해 DB 왕복을
 * 만드는 것은 SEO 로도 성능으로도 얻는 게 없다. 수백 개가 되면 그때 옮긴다
 * (→ docs/wiki/00-decisions/0013-dream-meanings-in-frontend.md).
 *
 * ── 왜 필요한가 ──────────────────────────────────────────────────────
 * 이 텍스트가 없으면 키워드 페이지 서른 장이 표제어만 바뀐 **똑같은 문서**가 된다.
 * 그런 얇은 페이지가 색인되면 사이트 전체 평가가 내려간다
 * (→ docs/wiki/30-seo/metadata-strategy.md). 소재마다 다른 내용이 있어야 페이지가
 * 존재할 이유를 갖는다.
 *
 * ── 반드시 지킬 것 ───────────────────────────────────────────────────
 * ⚠ **민간 해석이라고 화면에 명시한다.** 사실 주장이 아니다. 같은 꿈을 두고도 지역과
 *   시대에 따라 풀이가 갈리며, 어느 쪽이 맞는지 가릴 방법이 없다.
 * ⚠ **당첨과 잇지 않는다.** "이 꿈을 꾸면 좋은 일이 생긴다" 까지가 전해 오는 말이고,
 *   거기서 추첨 결과로 넘어가면 금지 표현이다
 *   (→ docs/wiki/40-domain/forbidden-expressions.md).
 * ⚠ 남의 해몽 사이트 문장을 옮기지 않는다. 널리 알려진 유래를 우리 말로 다시 썼다.
 *   근거로 삼은 것은 위키백과 '해몽' 항목과 『주공해몽서』계열로 전해지는 통설이다.
 * ⚠ **키는 백엔드 사전에 실제로 있는 표제어여야 한다.** 없는 슬러그를 넣으면 그 페이지는
 *   404 라 풀이가 영영 화면에 나오지 않는다. 30개 전부 `/api/dream/keywords` 로
 *   존재를 확인했다(2026-08-27, 표제어 4,802개 기준).
 */
export interface DreamMeaning {
  /** 소재를 한 줄로. 검색 결과 설명문에도 이 문장이 앞선다. */
  summary: string
  /** 왜 그렇게 풀이해 왔는지. 유래가 있으면 유래를, 없으면 상징을 적는다. */
  origin: string
  /** 갈래가 갈리는 지점. 한쪽으로만 말하지 않기 위해 둔다. 없으면 생략. */
  caveat?: string
}

