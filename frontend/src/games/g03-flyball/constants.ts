/* ── 물리 ────────────────────────────────────────────────────── */

/**
 * 중력(px/s²).
 *
 * ⚠ **900 → 100 으로 낮췄다**(2026-09-17, 사용자 요구 *"2~3초 만에 끝나지 않게, 장타는
 *   날아가는 걸 보여 달라"*). 체공은 `2·v0·sinθ/g` 라 **중력을 낮추는 것이 체공을 버는
 *   유일한 길**이다 — 초속도를 올리면 거리만 늘고 체공은 그만큼 늘지 않는다.
 * ⚠ **각도를 함께 낮춰야 한다.** 최고점은 `(v0 sinθ)²/2g` 라 g 를 낮추면 같이 치솟는다.
 *   기준각 38° 에서는 300m 타구의 최고점이 272px 이라 HUD 를 덮었다(→ `ANGLE_BASE`).
 */
export const GRAVITY = 103

/** 공기저항 `a = -k·v` 의 k (s⁻¹). */
export const DRAG_K = 0.1

/**
 * ★ 빗맞은 타구에만 걸리는 중력 배율.
 *
 * 사용자 요구: *"100m 이내일 경우는 공이 좀 더 빨리 떨어져도 될 듯해."* 맞는 지적이다 —
 * 어차피 실패인 타구를 2초 넘게 지켜보는 것은 기다림일 뿐이다.
 *
 * ⚠ **중력만 올리면 비거리도 같이 줄어든다.** 체공은 `v0/g`, 비거리는 `v0²/g` 에 비례하므로
 *   `g` 를 s 배 하고 `v0` 를 √s 배 하면 **비거리는 그대로 두고 체공만 1/√s** 로 줄일 수 있다.
 *   그래서 `V0_WEAK_*` 가 안타 구간(`V0_GOOD_LO`)보다 **오히려 크다** — 중력이 3배이기
 *   때문이지 더 세게 친 것이 아니다. 이 역전이 이상해 보여 "버그" 로 고치지 않도록 한다.
 * ⚠ `ANGLE_MAX_WEAK` 와 **함께** 동작한다. 중력만으로는 이른 쪽(각도가 커지는 쪽) 체공이
 *   1.5초 아래로 내려가지 않았다 — 빗맞은 공은 회전이 죽어 뜨지 않는 것이 물리적으로도 맞다.
 * 실측: 빗맞음 체공 1.3~2.2초 → **0.82~1.07초.**
 */
export const WEAK_GRAVITY_SCALE = 3.0

/**
 * 표시 거리 환산. **100m = 280px → 화면 x = 340.**
 *
 * ⚠ 8 → 6 → 4 → **2.8**. 세 번 모두 같은 이유다 — 이 게임의 규칙선이 시작 화면에 보여야
 *   한다. 문턱이 40 → 60 → 100m 로 오를 때마다 환산을 같이 낮춰 **기준선의 화면 위치를
 *   314 에 고정**했다. 세 번의 개편 내내 이 한 점이 움직이지 않았다.
 * ⚠ 최대 311m 는 871px 라 월드(1000px) 안에 든다.
 */
export const PX_PER_M = 2.8

/**
 * 이 거리를 넘겨야 번호를 얻는다. 못 넘기면 기회만 소모한다.
 *
 * ⚠ 60 → **100**(2026-09-17, 사용자 결정). 문턱이 오르면 **기준선의 화면 위치도 오른쪽으로
 *   밀린다** — `HIT_X + 100 × PX_PER_M = 474` 라 무대 폭(360)을 넘어 **시작 화면에서 선이
 *   사라진다.** 이 게임은 규칙이 "선을 넘겨라" 하나뿐이라 선이 안 보이면 무엇을 해야 하는지
 *   그림으로 전달할 수 없다. 그래서 `PX_PER_M` 을 4 → 2.4 로 함께 낮춰 선을 제자리(314)에
 *   붙들었다. **문턱을 만질 때마다 환산도 같이 만져야 한다** — 09-10, 09-17 에 이미 두 번
 *   같은 일을 했다.
 */
export const MIN_METERS = 100

/** 이 거리를 넘으면 장타. **타구가 뜨는 순간부터** 불이 붙는다(사용자 요구). */
export const LONG_METERS = 200

/** 이 거리를 넘으면 초대형. 완벽 판정은 언제나 여기에 든다. */
export const HUGE_METERS = 270

/* ── 타이밍 판정 ─────────────────────────────────────────────── */

/**
 * 판정 창(초). `|d| ≤` 이 값이면 그 판정이다.
 *
 * ⚠ **종전(0.05 / 0.11 / 0.18)보다 좁다.** 번호를 얻는 유효 창이 0.235초였는데, 그만큼
 *   넉넉하면 *"그냥 누르면 맞는 게임"* 이 된다(사용자 지적). 0.169초로 28% 좁혔다.
 *
 * ★ **창의 폭이 곧 결과의 비율이다**(2026-09-17, 사용자 지적 *"너무 장타가 많이 나오는데"*).
 *   유효 창(`±WIN_GOOD`) 안에서 각 구간이 차지하는 몫이 그대로 그 결과가 나올 확률이 된다.
 *   종전 배분(0.028 / 0.058)은 **장타 이상이 68%** 였다 — 번호를 얻으면 셋 중 둘이 장타라
 *   장타가 특별하지 않았다. 0.013 / 0.028 로 좁혀 **초대형 15% · 장타 18% · 안타 67%**,
 *   즉 **장타 이상 33%**(안타 세 번에 장타 한 번)로 맞췄다.
 *   ⚠ 비거리 구간(270m·200m)은 건드리지 않았다. **잘 맞았을 때의 보상은 그대로 두고
 *   그 일이 일어나는 빈도만 낮춘 것**이다 — 보상을 깎으면 장타가 시시해진다.
 *   ⚠ `WIN_PERFECT` 를 더 줄이지 않는 이유는 **프레임**이다. 입력은 프레임(16.7ms)에
 *   양자화되므로 창 폭(2×0.0115 = 23ms)이 그보다 좁아지면 노려서 맞출 수 없고 운이 된다.
 *
 * ★ **전체를 11% 더 좁혔다**(2026-09-17, 사용자 지적 *"너무 쉬워"*). ±85 → **±75ms**.
 *   종전 창은 사람 손의 오차(대략 ±45ms)를 **통째로 덮어** 대충 눌러도 늘 들어왔다.
 *   ⚠ 네 값을 **같은 비율로** 줄였다 — 하나만 줄이면 장타 비율(33%)이 틀어진다.
 */
export const WIN_PERFECT = 0.0115
export const WIN_GREAT = 0.025
export const WIN_GOOD = 0.075
export const WIN_WEAK = 0.125

/**
 * 판정별 초속도 구간(px/s). 창 안에서 `|d|` 에 선형 보간한다.
 *
 * ⚠ **종전의 `v0 = 252 + 606 × power^1.6` 을 버렸다**(2026-09-17). 지수 하나로 네 구간의
 *   거리를 동시에 맞추려니 한쪽을 고치면 다른 쪽이 어긋났고, 그 결과가 *"빗맞았는데 40m 를
 *   넘는다"* 였다. 구간마다 끝값을 못 박으면 **판정 이름이 곧 비거리 약속**이 되어 어긋날 수
 *   없다 — 빗맞으면 반드시 실패하고 안타 이상이면 반드시 성공한다.
 * ⚠ 안타 하단(170)과 빗맞음 상단(150) 사이에 **일부러 틈을 뒀다.** 경계에서 67m ↔ 58m 로
 *   건너뛰는데, 이 10m 가 "성공과 실패 사이에 회색지대가 없다" 를 만든다.
 */
export const V0_PERFECT_HI = 336
export const V0_PERFECT_LO = 309
export const V0_GREAT_LO = 259
export const V0_GOOD_LO = 177
export const V0_WEAK_HI = 285
