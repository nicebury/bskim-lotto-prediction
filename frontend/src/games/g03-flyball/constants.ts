/* ── 판정 ────────────────────────────────────────────────────── */

export type Judge = 'perfect' | 'great' | 'good' | 'weak' | 'miss'

/** 타이밍 오차(초) → 판정. 부호는 보지 않는다. */
export function judgeOf(delta: number): Judge {
  const d = Math.abs(delta)
  if (d <= WIN_PERFECT) return 'perfect'
  if (d <= WIN_GREAT) return 'great'
  if (d <= WIN_GOOD) return 'good'
  if (d <= WIN_WEAK) return 'weak'
  return 'miss'
}

/** 두 값 사이를 선형 보간. `DrawKit` 의 것과 같지만 물리 쪽에서 쓰려고 따로 둔다. */
function mix(a: number, b: number, t: number): number {
  return a + (b - a) * t
}

/**
 * 타이밍 오차 → 초속도(px/s). 헛스윙이면 0.
 *
 * ⚠ 창 안에서 **선형**으로 내려간다. 계단으로 두면 같은 판정 안에서 결과가 똑같아져
 *   "조금 더 잘 맞혔다" 는 감각이 사라진다.
 */
export function speedOf(delta: number): number {
  const d = Math.abs(delta)
  if (d <= WIN_PERFECT) {
    return mix(V0_PERFECT_HI, V0_PERFECT_LO, d / WIN_PERFECT)
  }
  if (d <= WIN_GREAT) {
    return mix(V0_PERFECT_LO, V0_GREAT_LO, (d - WIN_PERFECT) / (WIN_GREAT - WIN_PERFECT))
  }
  if (d <= WIN_GOOD) {
    return mix(V0_GREAT_LO, V0_GOOD_LO, (d - WIN_GREAT) / (WIN_GOOD - WIN_GREAT))
  }
  if (d <= WIN_WEAK) {
    return mix(V0_WEAK_HI, V0_WEAK_LO, (d - WIN_GOOD) / (WIN_WEAK - WIN_GOOD))
  }
  return 0
}

/**
 * 타이밍 오차 → 발사각(rad).
 *
 * ⚠ 빗맞음에는 **낮은 상한**(`ANGLE_MAX_WEAK`)이 걸린다. 그래야 이른 쪽 빗맞음이 높이 떠
 *   오래 머무는 일이 없다 — 어차피 실패인 타구를 오래 지켜보게 하지 않는다.
 */
export function angleOf(delta: number): number {
  const cap = judgeOf(delta) === 'weak' ? ANGLE_MAX_WEAK : ANGLE_MAX
  const deg = Math.min(cap, Math.max(ANGLE_MIN, ANGLE_BASE - delta * ANGLE_K))
  return (deg * Math.PI) / 180
}

/**
 * 타이밍 오차 → 이 타구에 걸리는 중력(px/s²).
 *
 * ⚠ 판정마다 중력이 다른 것은 **연출이 아니라 물리 설정**이다. 빗맞음은 `WEAK_GRAVITY_SCALE`
 *   배로 무겁고, 그만큼 초속도를 올려 두었으므로 비거리는 의도한 대로 나온다.
 */
export function gravityOf(delta: number): number {
  return judgeOf(delta) === 'weak' ? GRAVITY * WEAK_GRAVITY_SCALE : GRAVITY
}

/** 판정 → 화면에 띄우는 한 마디. 금지 표현을 쓰지 않는다(거리와 판정만 말한다). */
export function judgeLabel(j: Judge): string {
  if (j === 'perfect') return '완벽!'
  if (j === 'great') return '굿샷!'
  if (j === 'good') return '안타'
  if (j === 'weak') return '빗맞음'
  return ''
}
