/* ────────────────────────────────────────────────────────────
 * 물리 상수와 그 검산
 *
 * 감속은 **선형(쿨롱) 마찰**이다. 얼음 느낌은 지수 감쇠보다 이쪽이 훨씬 정확하다.
 *   v0 = V0_BASE + pull × V0_GAIN        (pull: 당김 길이 px)
 *   정지 거리 d = v0² / (2a)
 *
 * 설계는 해석식으로 잡고(v_min = √(2a·110.5), v_max = √(2a·294.5) → GAIN 4.0 · BASE 194),
 * **확정은 실측으로 한다.** 실제 루프는 오일러 적분이라 해석식보다 한 스텝만큼 더 간다.
 *
 * ── 실측 (a = 380, 각도 0, 실제 루프와 같은 dt·같은 식) ────────────
 *   pull  0 ~ 20.5   보드에 못 미친다 (레인에 선다)
 *   pull 21   ~ 28   행 8 (맨 아래)      pull 48   ~ 53   행 4
 *   pull 28.5 ~ 35   행 7               pull 53.5 ~ 58   행 3
 *   pull 35.5 ~ 41.5 행 6               pull 58.5 ~ 63   행 2
 *   pull 42   ~ 47.5 행 5               pull 63.5 ~ 68   행 1
 *                                       pull 68.5 ~ 72   행 0 (맨 위)
 *   pull 73   ~ 74.9 보드 위 공백에 선다 (헛투구)
 *   pull 75   ~ 80   **아웃**
 *
 * 한 행이 당김 5~7px 에 대응한다 — 손가락 해상도로 조절된다.
 * 좌우는 ±45° 안에서 **아홉 행 모두 다섯 열 전부** 도달한다(실측).
 *
 * ⚠ **최대 당김이 아웃에 닿아야 한다.** 처음에는 PULL_MAX 를 72 로 뒀는데, 실측해 보니
 *   끝까지 당겨도 맨 위 행에 얌전히 서서 **아웃이 한 번도 나지 않았다.** 그런데 화면에는
 *   아웃 라인이 그려져 있다 — 넘을 수 없는 선을 그려 두는 것은 화면이 하는 거짓말이고,
 *   동시에 "끝까지 당기는 것이 언제나 안전" 이 되어 세기를 조절할 이유가 사라진다.
 *   80 으로 올리면 보드 → 보드 밖 → 아웃 세 구간이 모두 손에 들어온다.
 * ⚠ 그래도 화면 밖으로 나가지 않는다 — 손가락 최대 y = 330 + 80 = 410 < 430.
 * ──────────────────────────────────────────────────────────── */

