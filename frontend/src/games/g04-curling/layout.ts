/**
 * G04 얼음판 컬링 — 화면 기하와 물리 상수.
 *
 * → 사양서: docs/wiki/20-design/game-g04-curling.md
 * → 계약:   docs/wiki/10-contracts/playground-game-contract.md
 *
 * ── ⚠ 왜 숫자를 여기 몰아 두는가 ───────────────────────────────────
 * 이 게임의 조작은 **당김 길이 하나**뿐이다. 그 길이가 보드 전체를 덮지 못하면(맨 아래 행에
 * 닿지 못하거나 맨 위 행을 넘겨 버리면) 게임이 통째로 성립하지 않는다. 그래서 기하와 물리
 * 수치를 **한 파일에 모아 함께 검산**한다 — 렌더와 물리에 흩어 놓으면 한쪽만 고치고 대응이
 * 깨진 것을 아무도 모른다.
 *
 * ── ⚠ 번호는 여기서 만들지 않는다 ─────────────────────────────────
 * 계약이 "게임 코드에 1~45 리터럴이 있으면 반려한다" 고 못 박았다. 이 파일은 **칸의 자리**
 * (행·열·좌표)만 정의한다. 칸 수조차 `cols × rows` 로 계산해 두므로 리터럴이 없다.
 *
 * ── ★ 2026-09-17 전면 개편 ────────────────────────────────────────
 * 보드형(칸에 번호가 적혀 있음) → **은닉형**(칸이 전부 뒷면)으로 바뀌었다. 그 결과 이 파일의
 * 전제 하나가 사라졌다 — 예전에는 "아래가 1~5, 위가 41~45" 라 **세기가 곧 번호 선택**이었고
 * 그것이 난이도 곡선이었다. 이제 어느 칸이든 값이 같으므로, 세기는 "보드 안에 넣는" 문제로
 * 바뀌고 난이도는 **꽝 칸과 장애물**이 만든다.
 */

