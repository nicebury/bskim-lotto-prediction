export interface Cell {
  readonly row: number
  readonly col: number
}

/**
 * ★ 한 칸의 상태 (2026-09-17 신설).
 *
 * 보드형이던 시절에는 칸의 번호를 `pool.board()` 가 알려 주었고 게임은 그것을 읽기만 했다.
 * 은닉형이 되면서 **칸의 상태는 게임이 소유한다** — 풀은 "번호 하나를 달라"(`awardHidden`)는
 * 요청만 받고 칸이라는 개념 자체를 모르기 때문이다.
 *
 * · `hidden`  아직 뒤집히지 않았다. 꽝인지 아닌지는 화면에 드러나지 않는다
 * · `blank`   뒤집었더니 꽝이었다. **다시 멈추면 또 꽝이다**(장애물이 아니다)
 * · `awarded` 번호를 얻었다. `value` 가 그 번호이고, 이 칸은 **장애물**이 된다
 *
 * ⚠ `value` 는 `awarded` 일 때만 뜻이 있다. 다른 상태에서 0 인 것은 "번호가 없다" 는 뜻이지
 *   0번 번호라는 뜻이 아니다 — 렌더가 `kind` 를 먼저 보고 분기한다.
 */
export type CellKind = 'hidden' | 'blank' | 'awarded'

export interface CellState {
  kind: CellKind
  value: number
}

/**
 * 칸의 배열 인덱스(0 ~ CELL_COUNT-1).
 *
 * ⚠ 예전에는 이 순서가 곧 번호 순서였다("아래가 작고 위가 크다"). 이제 칸에 번호가 붙어
 *   있지 않으므로 **순서 자체에는 의미가 없고**, 상태 배열을 찾아가는 색인일 뿐이다.
 *   그래도 행을 뒤집어 두는 것은 유지한다 — 꽝 자리를 뽑는 난수 스트림이 같은 시드에서
 *   같은 판을 만들어야 하고(계약: 재현성), 색인 규칙을 바꾸면 그 재현이 깨진다.
 */
export function boardIndex(row: number, col: number): number {
  return (BOARD.rows - 1 - row) * BOARD.cols + col
}

/** 칸 중심의 논리 좌표. */
export function cellCenter(row: number, col: number): { x: number; y: number } {
  return {
    x: BOARD.left + col * BOARD.cellW + BOARD.cellW / 2,
    y: BOARD.top + row * BOARD.cellH + BOARD.cellH / 2,
  }
}

/**
 * 좌표가 속한 칸. 보드 밖이면 `null` — 호출부가 헛투구로 처리한다.
 *
 * ⚠ 판정은 **스톤 중심**으로만 한다. 걸친 면적으로 판정하면 "어느 칸인지" 가 화면과
 *   어긋나는 순간이 생기고, 그것은 화면이 하는 거짓말이다.
 */
export function cellAt(x: number, y: number): Cell | null {
  if (x < BOARD.left || x >= BOARD.right) return null
  if (y < BOARD.top || y >= BOARD.bottom) return null
  return {
    col: Math.floor((x - BOARD.left) / BOARD.cellW),
    row: Math.floor((y - BOARD.top) / BOARD.cellH),
  }
}

/**
 * 칸 **가운데**에 제대로 멈췄는가. 경계 띠에 걸쳤으면 `false`.
 *
 * ⚠ 이 판정은 `cellAt` 과 **별개**다. `cellAt` 은 "어느 칸 위인가"(그림과 결과를 맞추는 일)
 *   이고, 이쪽은 "그 칸을 얻을 만큼 제대로 들어왔는가"(난이도)다. 둘을 한 함수로 합치면
 *   걸쳤을 때 **어느 칸에 걸쳤는지조차 알 수 없어져** 화면에 보여 줄 수가 없다.
 */
export function isCellHit(x: number, y: number, cell: Cell): boolean {
  const left = BOARD.left + cell.col * BOARD.cellW
  const top = BOARD.top + cell.row * BOARD.cellH
  return (
    x >= left + HIT_MARGIN_X &&
    x <= left + BOARD.cellW - HIT_MARGIN_X &&
    y >= top + HIT_MARGIN_Y &&
    y <= top + BOARD.cellH - HIT_MARGIN_Y
  )
}

