/**
 * ★ 꽝은 **확률로 굴리지 않는다. 봉투에서 뽑는다.**
 *
 * `BLANK_POOL` 개짜리 봉투에 꽝 `BLANK_COUNT` 장을 넣고 섞어, 볼을 만들 때마다 한 장씩
 * 꺼낸다. 그래서 **한 판의 꽝 수에 상한이 있고**(최대 2), 연달아 터지는 일이 구조적으로
 * 드물다. 확률을 굴리면 운이 나쁜 판에서 꽝만 다섯 번 나올 수 있고, 그것이 정확히
 * [[0014-number-playground]] 가 막으려던 "조작당했다" 는 정서다.
 *
 * G01 이 "12발에 꽝 두 장을 넣은 봉투" 로 먼저 쓴 방식과 같다.
 */
export const BLANK_POOL = 12
export const BLANK_COUNT = 2

/** 볼 여섯 개의 자리. 한 줄이라 **모든 볼이 언제나 집을 수 있다.** */
export function slotX(i: number): number {
  const step = (PILE_R - PILE_L) / (BALL_COUNT - 1)
  return PILE_L + i * step
}
