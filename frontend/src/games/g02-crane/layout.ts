/**
 * 왕복 속도(px/s). 핑퐁.
 *
 * ⚠ **난이도는 창이 만들고 속도는 조작 가능성을 만든다.** 둘을 같이 조이면 게임이 아니라
 *   벌이 된다. 그래서 "어렵다" 는 피드백에 창만 넓히지 않고 속도를 함께 내린다.
 *
 * 95 → **85**(2026-09-17). 창이 10.5px 이므로 창 안에 머무는 시간이
 * `21 ÷ 85 = 0.247초` 다(95 일 때는 0.177초). **누르는 타이밍이 ±0.124초까지 어긋나도
 * 집힌다** — 사람의 타이밍 정밀도를 생각하면 여기서부터 "조준" 이 된다.
 *
 * ⚠ 더 내리지 않는 이유: 왕복 편도가 `236 ÷ 85 = 2.78초` 다. 더 느리면 **겨눌 볼이
 *   올 때까지 기다리는 시간**이 길어져, 어려움 대신 지루함이 온다.
 */
export const MAG_SPEED = 85
