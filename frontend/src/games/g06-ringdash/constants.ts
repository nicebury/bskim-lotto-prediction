export const RING_R = 30
export const RING_LINE = 6
/** 링 한가운데 번호 볼. 숫자는 반드시 `draw.ball()` 로만 그린다(시각 언어 규칙 4). */
export const RING_BALL_R = 15

/**
 * ★ **몇 번째 링이 번호 링인가.** 1-기반 순번이고 나머지는 전부 꽝 링이다.
 *
 * ── 왜 난수가 아니라 고정 배치인가 ─────────────────────────────────
 * 사용자 지시는 *"6개를 통과하면 무조건 6개를 모으게 하지말고 … 20개정도는 통과해야 다
 * 모으는걸로 **잘 배치**해야 할거 같아"* 였다. 확률(30%)로 뽑으면 기댓값은 20개지만
 * **분산이 크다** — 운이 나쁘면 40개를 넘기고, 그때는 기회 9번으로 절대 못 채운다.
 * '잘 배치' 라는 말이 가리키는 것이 이 분산이다.
 *
 * ── 간격을 이렇게 잡은 이유 ────────────────────────────────────────
 * 첫 번호를 **2번째**에 준다. 첫 성공이 빨라야 "이 게임이 무엇을 주는지" 를 알고, 그 전에
 * 떨어지면 아무것도 모른 채 기회만 잃는다. 그 뒤로는 3~4개 간격으로 벌리고 마지막을
 * 20번째에 둔다.
 *
 * ⚠ 실측에서 기회 9번으로 모자라면 **난도가 아니라 이 배열을 먼저 앞당긴다.** 원인이
 *   어려움이 아니라 거리이기 때문이다.
 */
export const NUMBER_RING_ORDER: readonly number[] = [2, 6, 9, 13, 16, 20]

