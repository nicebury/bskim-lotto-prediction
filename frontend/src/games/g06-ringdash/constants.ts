/**
 * G06 링 통과 비행 — 튜닝 수치.
 *
 * → 사양서: docs/wiki/20-design/game-g06-ringdash.md
 *
 * ── ⚠ 왜 수치를 한 파일에 모으는가 ─────────────────────────────────
 * 이 게임은 **기획 원문이 직접 위험을 지적한 유일한 게임**이다 — *"난도 조절 필수. 너무
 * 어려우면 번호를 못 뽑고 이탈"*. 즉 앞으로 손댈 일이 가장 많은 것이 로직이 아니라 **수치**다.
 * 그때 물리 코드 사이를 뒤지게 하지 않으려고 전부 여기 둔다.
 *
 * ── ⚠ 아래 값을 임의로 어렵게 조정하지 않는다 ──────────────────────
 * 사양서가 못 박은 값이고, 원본 플래피류보다 **명백히 쉽게** 잡혀 있다. 실측에서
 * "기회 9번 안에 번호 6개" 를 못 채우면 **더 쉽게** 바꾸는 방향만 허용된다.
 */

/* ── 새 ───────────────────────────────────────────────────────── */

